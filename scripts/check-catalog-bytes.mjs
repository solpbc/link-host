import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { catalogFiles, catalogHashes } from "./catalog-snapshot.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));

test("committed catalog, pin and generated bytes match the snapshot", () => {
  const snapshotPath = path.join(root, "i18n/generated/snapshot.json");
  const snapshot = JSON.parse(fs.readFileSync(snapshotPath, "utf8"));
  const files = catalogFiles(root);
  const keys = Object.keys(snapshot).sort((a, b) => a.localeCompare(b, "en"));
  assert.deepEqual(files, keys);
  const hashes = catalogHashes(root);
  for (const rel of files) assert.equal(hashes[rel], snapshot[rel], rel);
});
